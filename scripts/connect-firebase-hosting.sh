#!/usr/bin/env bash
# Run in the project's Google Cloud Shell after GitHub CLI device login.
set -euo pipefail
set +x
umask 077

br_project='back-round'
br_repo='1309-boy/back-round'
br_service='github-hosting-deploy'
br_account="${br_service}@${br_project}.iam.gserviceaccount.com"

for br_tool in gcloud gh python3; do
  command -v "$br_tool" >/dev/null || { echo "Required command not found: $br_tool" >&2; exit 1; }
done
if [[ "$(gh api user --jq .login)" != '1309-boy' ]]; then
  echo 'GitHub CLI must be signed in as 1309-boy. Nothing was changed.' >&2
  exit 1
fi
gcloud projects describe "$br_project" --format='value(projectId)' >/dev/null

# A rerun never replaces a previously registered deployment credential.
br_existing=$(gh secret list --repo "$br_repo" --json name --jq '.[].name')
if [[ "$br_existing" == *'FIREBASE_SERVICE_ACCOUNT'* ]]; then
  if printf '%s\n' "$br_existing" | python3 -c 'import sys; sys.exit(0 if "FIREBASE_SERVICE_ACCOUNT" in sys.stdin.read().splitlines() else 1)'; then
    echo 'FIREBASE_SERVICE_ACCOUNT already exists; no new key was created.'
    exit 0
  fi
fi

if ! gcloud iam service-accounts describe "$br_account" --project "$br_project" >/dev/null 2>&1; then
  gcloud iam service-accounts create "$br_service" --project "$br_project" \
    --display-name='Back round GitHub Hosting deploy' --quiet
fi
for br_role in roles/firebasehosting.admin roles/serviceusage.apiKeysViewer; do
  gcloud projects add-iam-policy-binding "$br_project" \
    --member="serviceAccount:${br_account}" --role="$br_role" --condition=None --quiet >/dev/null
done

br_temp_dir=$(mktemp -d)
br_key_file="$br_temp_dir/key.json"
br_uploaded=0
cleanup() {
  br_status=$?
  trap - EXIT
  # If upload failed, revoke only the key generated by this invocation.
  if [[ "$br_uploaded" != 1 && -s "$br_key_file" ]]; then
    br_key_id=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["private_key_id"])' "$br_key_file" 2>/dev/null) || br_key_id=''
    if [[ -n "$br_key_id" ]]; then
      if ! gcloud iam service-accounts keys delete "$br_key_id" \
        --iam-account="$br_account" --project="$br_project" --quiet >/dev/null; then
        echo 'Could not revoke the new key after upload failure. Remove it in Google Cloud Service Accounts > Keys.' >&2
      fi
    fi
  fi
  rm -f "$br_key_file"
  rmdir "$br_temp_dir" 2>/dev/null || true
  exit "$br_status"
}
trap cleanup EXIT

gcloud iam service-accounts keys create "$br_key_file" --iam-account="$br_account" --project "$br_project" --quiet
# gh encrypts the file locally with GitHub's repository public key before upload.
gh secret set FIREBASE_SERVICE_ACCOUNT --repo "$br_repo" < "$br_key_file"
br_uploaded=1
echo 'SUCCESS: Back round Firebase deployment Secret registered. No private key was printed.'
